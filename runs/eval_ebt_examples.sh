#!/bin/bash
################################################################################
# EBT 评估使用示例
# 展示如何在不同任务上评估 checkpoint
################################################################################

# 设置 checkpoint 路径（根据实际情况修改）
CHECKPOINT="/mnt/shared-storage-user/puyuan/code/nova/logs/checkpoints/ebt-xxs-bs_256_s1_lr_0.0012_*/epoch=*-step=*-valid_loss=*.ckpt"

# 如果有多个 checkpoint，选择最新的
LATEST_CKPT=$(ls -t $CHECKPOINT 2>/dev/null | head -n 1)

if [ -z "$LATEST_CKPT" ]; then
    echo "❌ 未找到 checkpoint，请先训练模型或修改路径"
    echo "示例路径: logs/checkpoints/ebt-xxs-.../epoch=10-step=50000.ckpt"
    exit 1
fi

echo "📦 使用 checkpoint: $LATEST_CKPT"
echo ""

################################################################################
# 示例 1: 在 NanoChat 测试集上评估 (PPL)
################################################################################

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "示例 1: NanoChat 数据集评估 (计算 PPL)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

CKPT_PATH="$LATEST_CKPT" \
EVAL_TASK="nanochat" \
LIMIT_TEST_BATCHES=50 \
bash runs/eval_ebt.sh

echo ""
echo ""

################################################################################
# 示例 2: GSM8K 数学推理任务
################################################################################

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "示例 2: GSM8K 数学推理任务"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

CKPT_PATH="$LATEST_CKPT" \
EVAL_TASK="gsm8k" \
LIMIT_TEST_BATCHES=100 \
BATCH_SIZE=4 \
bash runs/eval_ebt.sh

echo ""
echo ""

################################################################################
# 示例 3: ARC 科学问答任务
################################################################################

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "示例 3: ARC 科学问答任务"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

CKPT_PATH="$LATEST_CKPT" \
EVAL_TASK="arc" \
LIMIT_TEST_BATCHES=100 \
bash runs/eval_ebt.sh

echo ""
echo ""

################################################################################
# 完成
################################################################################

echo "✅ 所有示例评估完成！"
echo ""
echo "💡 提示:"
echo "   - 修改 LIMIT_TEST_BATCHES 控制测试样本数 (-1 = 全部)"
echo "   - 修改 BATCH_SIZE 根据 GPU 内存调整"
echo "   - 修改 GPUS 控制使用的 GPU (例如 GPUS='[0,1]')"
echo "   - 设置 USE_WANDB=true 启用 WandB 日志"
